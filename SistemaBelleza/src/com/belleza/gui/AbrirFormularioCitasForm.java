    private void btnAgendarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgendarActionPerformed
        try {
            //obtiene los datos de las casillas
            String cliente = txtCliente.getText().trim();
            String servicio = txtServicio.getText().trim();
            double precioServicio = Double.parseDouble(txtPrecioServicio.getText().trim());
            LocalDate fecha = LocalDate.parse(txtFecha.getText().trim());
            LocalTime hora = LocalTime.parse(txtHora.getText().trim());

            //añadiendolo a la tabla Cita
            Cita nuevaCita = new Cita(
                0,
                cliente,
                nombreEmpleadoActual,
                servicio,
                precioServicio,
                fecha,
                hora
            );
            authService.agregarCita(nuevaCita);
            JOptionPane.showMessageDialog(this, "Cita registrada con éxito.");//mostrando mensaje de confirmacion
            this.dispose();//cierra el formulario luego de ingresar el producto con exito
        }
        catch (HeadlessException | NumberFormatException | java.time.format.DateTimeParseException ex){
            JOptionPane.showMessageDialog(this, "Error en el formato de fecha, hora o números: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgendarActionPerformed

