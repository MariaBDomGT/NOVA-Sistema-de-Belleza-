    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        try {
            if (cmboxServicio.getSelectedItem() == null) {//si la seleccion del combobox es vacia
                JOptionPane.showMessageDialog(this, "Seleccione un servicio.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String seleccionado = cmboxServicio.getSelectedItem().toString();//seleccionando un dato en el combobox
            String idServ = seleccionado.split(" - ")[0];//seleccionando el id del servicio

            //si el servicio encontrado es igual al servicio almacenado
            Servicio servEncontrado = gestorServicios.listarTodos().stream()
                    .filter(s -> s.getId().equalsIgnoreCase(idServ))
                    .findFirst()
                    .orElse(null);

            if (servEncontrado == null) {//si el servicio encontrado esta vacio
                return;
            }
            try {
                String cantStr = txtCantidad.getText().trim();//tomando el dato de la caja de texto
                if (cantStr.isEmpty()) {//comprobando si la caja de texto esta vacio
                    JOptionPane.showMessageDialog(this, "Ingrese una cantidad.", "Aviso", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                int cant = Integer.parseInt(cantStr);//convirtiendo la cantidad en un entero
                
                DetalleVenta dv = new DetalleVenta(cant, servEncontrado.getPrecio());//guardando en el detalle de la venta
                
                this.detalleSeleccionado = dv;
                this.nombreServicioSeleccionado = servEncontrado.getNombre();
                this.cantidadSeleccionada = cant;
                this.precioSeleccionado = servEncontrado.getPrecio();

                //calculando el subtotal y la ganancia del local
                double subTotal = servEncontrado.getPrecio() * cant;
                double ganancia = servEncontrado.getPrecio() * cant;

                JOptionPane.showMessageDialog(this, "Servicio agregado a la venta.");
                this.dispose();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ingrese un numero valido para la cantidad.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al almacenar el servicio." + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnAceptarActionPerformed

