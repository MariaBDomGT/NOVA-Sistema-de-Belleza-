    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            //tomando los datos de las cajas de datos
            String id = txtID.getText().trim();
            String categoria = cmboxCategoria.getSelectedItem().toString();
            String nombre = txtNombre.getText().trim();
            String descripcion = txtDescripcion.getText().trim();
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            int duracion = Integer.parseInt(txtDuracion.getText().trim());
            
            if(id.isEmpty() || nombre.isEmpty()){//comprobando si el id y el nombre estan vacios
               JOptionPane.showMessageDialog(this, "El ID y el nombre son obligatorios.", "Aviso", JOptionPane.WARNING_MESSAGE);
               return;
            }
            
            Servicio nuevoServicio = null;//inicializando un objeto Servicio vaciado
            
            //mostrando las categorias 
            switch(categoria){
                case "Barberia"://si la categoria es barberia
                    boolean toalla = chboxToallaCaliente.isSelected();
                    String estiloBarba = txtEstiloBarba.getText().trim();
                    nuevoServicio = new Barberia(id, nombre, descripcion, precio, duracion, toalla, estiloBarba);
                    break;
                case "Estetica"://si la categoria es estetica
                    String tipoPiel = txtTipoPiel.getText().trim();
                    nuevoServicio = new Estetica(id, nombre, descripcion, precio, duracion, tipoPiel, true);
                    break;
                case "Uñas"://si la categoria es uñas
                    String materialEsmalte = txtMaterialEsmalte.getText().trim();
                    nuevoServicio = new Unas(id, nombre, descripcion, precio, duracion, materialEsmalte, true);
                    break;
                default:
                    JOptionPane.showMessageDialog(this, "Categoría no valida.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
            }
            
            if(nuevoServicio != null){//si el nuevo servicio no esta vacio
                gestorServicios.registrarServicio(nuevoServicio);//registrando un nuevo servicio
                JOptionPane.showMessageDialog(this, "Servicio registrado con exito.");
                this.dispose();
            }
        }
        catch (NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Asegurese de que el precio y la duracion sean numeros validos.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

