    private void actualizarTablaVenta(){//actualizando la tabla de vetnas
        modeloTablaItems.setRowCount(0);//devuelve la cantidad de filas
        
        //recorriendo los datos de la tabla
        for(String[] item : itemFactura){
            modeloTablaItems.addRow(item);
        }
        
        txtTotal.setText(String.format("Q%.2f", ventaActual.getTotal()));//mostrando el total de la venta
        
        //cambiando la fuente de la tabla
        tbVentasFact.getTableHeader().setFont(new java.awt.Font("Sitka Text", 1, 13));
        tbVentasFact.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
        
        for(int a = 0; a < tbVentasFact.getModel().getColumnCount(); a++){
            javax.swing.table.TableColumn columna = tbVentasFact.getColumnModel().getColumn(a);
            
            int anchoEncabezado = tbVentasFact.getTableHeader().getFontMetrics(tbVentasFact.getTableHeader().getFont()).stringWidth(tbVentasFact.getColumnName(a))+50;
            int anchoMaximoDatos = anchoEncabezado;
            for(int fila = 0; fila < tbVentasFact.getRowCount(); fila++){
                Object valor = tbVentasFact.getValueAt(fila, a);
                if(valor != null){
                    int anchoCelda = tbVentasFact.getFontMetrics(tbVentasFact.getFont()).stringWidth(valor.toString())+20;
                    if(anchoCelda > anchoMaximoDatos){
                        anchoMaximoDatos = anchoCelda;
                    }
                }
            }
            
            columna.setPreferredWidth(anchoMaximoDatos);
        }
    }

