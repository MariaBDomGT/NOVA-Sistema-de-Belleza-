    private void btnCobrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCobrarActionPerformed
        try{
            //comprobando si los items no estan en la factura
            if(itemFactura.isEmpty()){
                JOptionPane.showMessageDialog(this, "No hay ítems agregados a la venta.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }
            try{
                String cliente = txtCliente.getText().trim();//tomando el nombre del cliente
                if(cliente.isEmpty()){//comprobando si el cliente no esta
                    cliente = "Cliente General";
                }
                ventaActual.setCliente(cliente);//mostrando al cliente
                authService.agregarVenta(ventaActual);//agregando a la venta
                
                //generando factura PDF usando la clase Factura
                Factura f = new Factura(ventaActual.getIdVenta(), "FAC-00" + ventaActual.getIdVenta(), ventaActual.getFecha(), ventaActual.getTotal());
                String nombreLimpio = cliente.replace(" ", "_").replace("/", "-");
                String fechaStr = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss"));
                String nombreArchivo = "Factura_" + nombreLimpio + " _ " + fechaStr + ".pdf";
                
                //Obtener la ruta del escritorio del usuario actual
                String rutaEscritorio = System.getProperty("user.home") + java.io.File.separator + "Desktop";
                java.io.File carpetaNOVA = new java.io.File(rutaEscritorio, "NOVA_Reportes_y_Facturas");
                
                //si la carpeta no existe, la crea
                if(!carpetaNOVA.exists()){
                    carpetaNOVA.mkdirs();
                }
                
                //despues de crear el nombre del archivo
                String rutaCompletaPDF = new java.io.File(carpetaNOVA, nombreArchivo).getAbsolutePath();
                boolean exito = f.exportarPDF(rutaCompletaPDF, cliente, itemFactura);
                
                if(exito){    
                    JOptionPane.showMessageDialog(this, "Venta cobrada con exito./Factura generada: " + nombreArchivo + ".pdf", "Exito", JOptionPane.INFORMATION_MESSAGE);
                    
                    //limpiando los campos de la tabla
                    itemFactura.clear();
                    modeloTablaItems.setRowCount(0);
                    txtTotal.setText("Q.00");
                    txtCliente.setText("Cliente General");
                }
                else{
                    JOptionPane.showMessageDialog(this, "Error al generar el PDF de la factura.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
            catch(Exception ex){
                JOptionPane.showMessageDialog(this, "Error al cobrar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(Exception ex){
            JOptionPane.showMessageDialog(this, "Error, por favor ingrese datos validos" + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCobrarActionPerformed

