    private void btnAgregarProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarProductoActionPerformed
        agregarProductoForm form = new agregarProductoForm(authService, gestorServicios);//referenciando al formulario para agregar un producto
        form.setVisible(true);
        
        //sirve para que se actualiza la tabla luego de ingresar el producto
        form.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent e){
                if(form.detalleSeleccionado != null){
                    ventaActual.agregarDetalle(form.detalleSeleccionado);   
                    String nombre = form.nombreProductoSeleccionado;
                    int cant = form.cantidadSeleccionada;
                    double precio = form.precioSeleccionado;
                    double subtotal = precio*cant;
                    
                    itemFactura.add(new String[]{
                        nombre,
                        String.valueOf(cant),
                        String.format("%.2f", precio),
                        String.format("%.2f", subtotal)
                    });
                    actualizarTablaVenta();
                }
            }
        });
    }//GEN-LAST:event_btnAgregarProductoActionPerformed

