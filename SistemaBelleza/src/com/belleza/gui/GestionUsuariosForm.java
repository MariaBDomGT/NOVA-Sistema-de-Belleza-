    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try{
            int fila = tbUsuario.getSelectedRow();//seleccion para una fila de la tabla
            
            //si el usuario no selecciona una tabla
            if(fila == -1){
                JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            String username = (String) modeloTabla.getValueAt(fila, 1);//mostrando la segunda columna de la tabla
            
            //mensaje de confirmacion
            int confirm = JOptionPane.showConfirmDialog(this, "¿Desea eliminar al usuario '" + username + "'?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if(confirm == JOptionPane.YES_OPTION){
                if(authService.eliminarUsuario(username)){
                    cargaDatosTabla();
                    JOptionPane.showMessageDialog(this, "Usuario eliminado de la base de datos.");
                }
                else{
                    JOptionPane.showMessageDialog(this, "No se puede eliminar el usuario.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

