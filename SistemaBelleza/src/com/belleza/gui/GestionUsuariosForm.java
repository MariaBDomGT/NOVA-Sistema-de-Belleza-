    private void cargaDatosTabla(){//metodo para mostrar los datos a la tabla
        modeloTabla.setRowCount(0);//devuelve la cantidad de filas
        
        //recorriendo la lista de usuarios
        for(Usuario u : authService.listarUsuarios()){
            modeloTabla.addRow(new Object[]{
               u.getIdUsuario(),
                u.getUsername(),
                u.getNombre() + " " + u.getApellido(),
                u.getRol(),
                u.isEstado() ? "ACTIVO" : "INACTIVO"
            });
        }
        
        //cambiando la fuente de la tabla
        tbUsuario.getTableHeader().setFont(new java.awt.Font("Sitka Text", 1, 13));
        tbUsuario.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
        
        for(int a = 0; a < tbUsuario.getModel().getColumnCount(); a++){
            javax.swing.table.TableColumn columna = tbUsuario.getColumnModel().getColumn(a);
            
            int anchoEncabezado = tbUsuario.getTableHeader().getFontMetrics(tbUsuario.getTableHeader().getFont()).stringWidth(tbUsuario.getColumnName(a))+50;
            int anchoMaximoDatos = anchoEncabezado;
            for(int fila = 0; fila < tbUsuario.getRowCount(); fila++){
                Object valor = tbUsuario.getValueAt(fila, a);
                if(valor != null){
                    int anchoCelda = tbUsuario.getFontMetrics(tbUsuario.getFont()).stringWidth(valor.toString())+20;
                    if(anchoCelda > anchoMaximoDatos){
                        anchoMaximoDatos = anchoCelda;
                    }
                }
            }
            
            columna.setPreferredWidth(anchoMaximoDatos);
        }
    }

