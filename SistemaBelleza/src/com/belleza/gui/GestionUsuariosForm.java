    private void btnCambiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarActionPerformed
        int fila = tbUsuario.getSelectedRow();//seleccion una fila de la tabla
        
        //si el usuario no selecciona una tabla
        if(fila == -1){
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String username = (String) modeloTabla.getValueAt(fila, 1);//muestra la fila dos de la tabla
        Usuario u = authService.buscarUsuario(username);//buscando al usuario
        if(u != null){//si u no esta vacio
            authService.estadoUsuario(username, !u.isEstado());//cambiando el estado del usuario
            cargaDatosTabla();//mostrando los datos de la tabla
            JOptionPane.showMessageDialog(this, "Estado actualizado correctamente");//mensaje emergente en pantalla
        }
    }//GEN-LAST:event_btnCambiarActionPerformed

