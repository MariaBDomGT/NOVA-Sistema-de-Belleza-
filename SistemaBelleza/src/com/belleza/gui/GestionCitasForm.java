    private void cargaDatosCita(){
        modeloTabla.setRowCount(0);//devuelve la cantidad de filas
        
        //reocrre la lista de citas
        for(Cita c : authService.listarCitas()){
            //agrega una fila al modelo
            modeloTabla.addRow(new Object[]{
                c.getIdCita(),
                c.getCliente(),
                c.getEmpleado(),
                c.getServicio(),
                String.format("Q%.2f", c.getPrecioServicio()),
                c.getFecha(),
                c.getHora(),
                c.getEstado()
            });
        }
        
        //cambiando la fuente de la tabla 
        tbCita.getTableHeader().setFont(new java.awt.Font("Sitka Text", 1, 13));
        tbCita.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
        
        for(int a = 0; a < tbCita.getModel().getColumnCount(); a++){
            javax.swing.table.TableColumn columna = tbCita.getColumnModel().getColumn(a);
            
            int anchoEncabezado = tbCita.getTableHeader().getFontMetrics(tbCita.getTableHeader().getFont()).stringWidth(tbCita.getColumnName(a))+50;
            int anchoMaximoDatos = anchoEncabezado;
            for(int fila = 0; fila < tbCita.getRowCount(); fila++){
                Object valor = tbCita.getValueAt(fila, a);
                if(valor != null){
                    int anchoCelda = tbCita.getFontMetrics(tbCita.getFont()).stringWidth(valor.toString())+20;
                    if(anchoCelda > anchoMaximoDatos){
                        anchoMaximoDatos = anchoCelda;
                    }
                }
            }
            
            columna.setPreferredWidth(anchoMaximoDatos);
        }
    }

