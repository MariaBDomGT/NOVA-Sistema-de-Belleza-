    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        //Verifica que se haya seleccionado una fila
        int fila = tbCita.getSelectedRow();
        if(fila == -1){
            JOptionPane.showMessageDialog(this, "Seleccione una cita de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        //Obtener el ID de la cita
        int idCita = (int) modeloTabla.getValueAt(fila, 0);
        
        //Confirmar la accion
        int confirm = JOptionPane.showConfirmDialog(this, "¿Marcar la cita ID " + idCita + " como FINALIZADA", "Confirmar", JOptionPane.YES_NO_OPTION);
        
        if(confirm == JOptionPane.YES_OPTION){
            try{
                authService.actualizarCita(idCita, "FINALIZADO");
                cargaDatosCita();
                JOptionPane.showMessageDialog(this, "Cita finalizada correctamente");
            }
            catch(Exception ex){
                JOptionPane.showMessageDialog(this, "Error al actualizar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnFinalizarActionPerformed

