    private void btnCancelarEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarEliminarActionPerformed
        try{
            int fila = tbCita.getSelectedRow();//selecciona una fila de la tabla
            
            //si el usuario no selecciona una fila
            if(fila == -1){
                JOptionPane.showMessageDialog(this, "Seleccione una cita de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            int id = (int) modeloTabla.getValueAt(fila, 0);//mostrando los datos de la tabla
            
            //mensaje que confirma la seleccion
            int confirm = JOptionPane.showConfirmDialog(this, "¿Desea cancelar/eliminar la cita ID " + id + "?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if(confirm == JOptionPane.YES_OPTION){
                if(authService.eliminarCita(id)){
                    cargaDatosCita();
                    JOptionPane.showMessageDialog(this, "Cita eliminada de la base de datos.");
                }
                else{
                    JOptionPane.showMessageDialog(this, "Cita eliminada de la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error");
        }
    }//GEN-LAST:event_btnCancelarEliminarActionPerformed

