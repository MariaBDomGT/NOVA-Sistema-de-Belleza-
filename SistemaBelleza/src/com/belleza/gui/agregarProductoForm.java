    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        try {
            if (cmboxProducto.getSelectedItem() == null) {//si la seleccion del combobox esta vacio
                JOptionPane.showMessageDialog(this, "Seleccione un producto.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String seleccionado = cmboxProducto.getSelectedItem().toString();//seleccionando un dato del combobox
            int idProd = Integer.parseInt(seleccionado.split(" ")[0]);//mostrando los datos del id 

            //si el producto seleccionado es igual al producto que esta en la base de datos
            Producto prodEncontrado = authService.getInventario().stream()
                    .filter(p -> p.getIdProducto() == idProd)
                    .findFirst()
                    .orElse(null);

            if (prodEncontrado == null) {//si el producto encontrado esta vacio
                return;
            }
            try {
                String cantStr = txtCantidad.getText().trim();//tomando el dato de la caja de texo
                if (cantStr.isEmpty()) {//comprobando si la cantidad esta vacia
                    JOptionPane.showMessageDialog(this, "Ingrese una cantidad.", "Aviso", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                int cant = Integer.parseInt(cantStr);//convirtiendo la cantidad a un entero

                if (cant > prodEncontrado.getStock()) {//si la cantidad es mayor al stock almacenado
                    JOptionPane.showMessageDialog(this, "No hay suficiente stock. stock actual: " + prodEncontrado.getStock(), "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                
                //almacenando los detalles de la venta
                DetalleVenta dv = new DetalleVenta(cant, prodEncontrado.getPrecioVenta());
                dv.setGanancia((prodEncontrado.getPrecioVenta() - prodEncontrado.getPrecioCompra()) * cant);//calculando la ganacia del local
                
                this.detalleSeleccionado = dv;
                this.nombreProductoSeleccionado = prodEncontrado.getNombre();
                this.cantidadSeleccionada = cant;
                this.precioSeleccionado = prodEncontrado.getPrecioVenta();

                prodEncontrado.actualizarStock(-cant);//restando la cantidad seleccionada al stock almacenado
                inventarioDAO.actualizarStock(prodEncontrado.getIdProducto(), prodEncontrado.getStock());//actualizando stock del inventario

                //creando las variables para calcular las ventas
                double subTotal = prodEncontrado.getPrecioVenta() * cant;
                double ganancia = (prodEncontrado.getPrecioVenta() - prodEncontrado.getPrecioCompra()) * cant;

                JOptionPane.showMessageDialog(this, "Producto agregado a la venta.");
                this.dispose();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Ingrese un numero valido para la cantidad.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(SQLException ex){
            JOptionPane.showMessageDialog(this, "Error al actualizar el stock." + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnAceptarActionPerformed

