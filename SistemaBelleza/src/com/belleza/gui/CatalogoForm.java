    private void btnCambiarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCambiarActionPerformed
        int fila = tbServicios.getSelectedRow();//para seleccionar una fila de la tabla
        
        //si el usuario no selecciona una fila
        if(fila == -1){
            JOptionPane.showMessageDialog(this, "Seleccione un servicio de la tabla.", "Atencion", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String id = (String) modeloTabla.getValueAt(fila, 0);//mostrando el contenido de la primera fila
        Servicio s = gestorServicios.buscarPorId(id);//buscando por el id del servicio
        
        //si el servicio no esta vacio
        if(s != null){
            gestorServicios.cambiarEstadoDisponibilidad(id, !s.isActivo());//cambiando el estado del servicio
            actualizarTabla();//actualizando la tabla
            JOptionPane.showMessageDialog(this, "Estado actualizado correctamente");//mostrando mensaje emergente
        }
    }//GEN-LAST:event_btnCambiarActionPerformed

