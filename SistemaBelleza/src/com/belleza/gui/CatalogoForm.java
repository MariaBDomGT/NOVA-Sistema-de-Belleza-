    private void actualizarTabla(){//metodo para actualizar los datos de la tabla
        modeloTabla.setRowCount(0);//devuelve la cantidad de filas
        
        //lista de los servicios
        List<Servicio> lista = chboxMostrarDisponibles.isSelected() ? gestorServicios.listarDisponibles() : gestorServicios.listarTodos();
        
        //recorriendo la cita
        for(Servicio s : lista){
            //agrega una fila al modelo
            modeloTabla.addRow(new Object[]{
                s.getId(),
                s.getClass().getSimpleName(),
                s.getNombre(),
                String.format("Q%.2f", s.getPrecio()),
                s.getDuracionMinutos() + "min",
                s.isActivo() ? "Disponible" : "No disponible",
                s.getDetalleEspecialidad()
            });
        }
        
        //cambiando la fuente de la tabla
        tbServicios.getTableHeader().setFont(new java.awt.Font("Sitka Text", 1, 13));
        tbServicios.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
        
        for(int a = 0; a < tbServicios.getModel().getColumnCount(); a++){
            javax.swing.table.TableColumn columna = tbServicios.getColumnModel().getColumn(a);
            
            int anchoEncabezado = tbServicios.getTableHeader().getFontMetrics(tbServicios.getTableHeader().getFont()).stringWidth(tbServicios.getColumnName(a))+50;
            int anchoMaximoDatos = anchoEncabezado;
            for(int fila = 0; fila < tbServicios.getRowCount(); fila++){
                Object valor = tbServicios.getValueAt(fila, a);
                if(valor != null){
                    int anchoCelda = tbServicios.getFontMetrics(tbServicios.getFont()).stringWidth(valor.toString())+20;
                    if(anchoCelda > anchoMaximoDatos){
                        anchoMaximoDatos = anchoCelda;
                    }
                }
            }
            
            columna.setPreferredWidth(anchoMaximoDatos);
        }
    }

