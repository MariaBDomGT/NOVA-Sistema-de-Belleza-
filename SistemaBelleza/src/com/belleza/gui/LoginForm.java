    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        try {
            //tomando los datos de las cajas de texto
            String user = txtUsuario.getText().trim();
            char[] passChars = txtPassword.getPassword();
            
            if(passChars.length == 0){//si la conraseña es igual a 0
                JOptionPane.showMessageDialog(this, "Por favor ingrese su contraseña");
                return;
            }
            
            String pass = new String(passChars).trim();//tomando la contraseña
            
            Usuario usuario = authService.login(user, pass);//agregando los datos al metodo login
            if(usuario != null){//si el usuario no esta vacio
                JOptionPane.showMessageDialog(this, "Bienvenido, " + usuario.getNombre() + " [" + usuario.getRol() + "]");
                //abriendo el menu correspondiente (dependiendo del rol) y cerrar el login
                dispose();
                switch(usuario){
                    case Administrador admin -> {
                        admin.setAuthService(authService);
                        admin.setGestorServicios(gestorServicios);
                        new MenuAdminForm(admin, authService, gestorServicios).setVisible(true);
                    }
                    case Empleado emp -> {
                        emp.setAuthService(authService);
                        emp.setGestorServicios(gestorServicios);
                        new MenuEmpleadoForm(emp, authService, gestorServicios).setVisible(true);
                    }
                    default -> {
                        System.out.println("Opcion no valida");
                    }
                }
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Credenciales incorrectas o usuario inactivo.", "Error de Acceso", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btnIniciarSesionActionPerformed

