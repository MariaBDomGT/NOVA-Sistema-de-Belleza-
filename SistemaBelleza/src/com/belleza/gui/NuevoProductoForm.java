    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            //obteniendo los datos de los campos
            String nombre = txtNombre.getText().trim();
            String descripcion = txtDescripcion.getText().trim();
            String marca = txtMarca.getText().trim();
            double precioCompra = Double.parseDouble(txtPrecioCompra.getText().trim());
            double precioVenta = Double.parseDouble(txtPrecioVenta.getText().trim());
            int stockInicial = Integer.parseInt(txtStockInicial.getText().trim());
            int stockMinimo = Integer.parseInt(txtStockMinimo.getText().trim());
            
            String catSeleccionado = cmboxTipo.getSelectedItem().toString();//para la seleccion del combobox
            CategoriaProducto cat = new CategoriaProducto();//nombrando una nueva categoria
            
            if(catSeleccionado.equals("DAMA")){//si la categora es dama
                cat.setIdCategoria(1);
            }
            else if(catSeleccionado.equals("CABALLERO")){//si la categoria es caballero
                cat.setIdCategoria(2);
            }
            else if(catSeleccionado.equals("NIÑOS")){//si la categoria es niños
                cat.setIdCategoria(3);
            }
            
            TipoProducto tipo = TipoProducto.valueOf(catSeleccionado);//seleccionando el tipo de producto
            
            //añadiendo nuevos productos
            Producto p = new Producto(
                0,
                nombre,
                descripcion,
                marca,
                precioCompra,
                precioVenta,
                stockInicial,
                stockMinimo,
                cat,
                tipo
            );
            inventarioDAO.insertarProducto(p);//llamando la insercion del producto al DAO de inventario
            authService.getInventario().add(p);//mostrando al inventario y añadiendolo
            JOptionPane.showMessageDialog(this, "Producto registrado con éxito.");
            this.dispose();//cierra el formulario luego de ingresar el producto con exito
        }
        catch (HeadlessException | NumberFormatException | SQLException ex){
            JOptionPane.showMessageDialog(this, "Error en los datos: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

