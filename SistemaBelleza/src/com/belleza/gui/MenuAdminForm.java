    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        //generando el archivo .xlsx
        Reporte reporte = new Reporte(1, "Ventas_y_Ganancias", new Date(), new Date(), "EXCEL");
        String[] encabezados = {"ID Venta", "Fecha", "Cliente", "Total (Q)", "Ganancia Neta (Q)"};//creando los encabezados del archivo
        List<Object[]> datos = new ArrayList<>();//creando un nuevo array list
        
        //recorriendo el listado de ventas
        for(Venta v : authService.listarVentas()){
            datos.add(new Object[]{
                v.getIdVenta(),
                v.getFecha().toString(),
                v.getCliente(),
                v.getTotal(),
                v.getGananciaVenta()
            });
        }
        
        //asignando un nombre al archivo
        String fechaStr = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss"));
        String nombreArchivo = "Reporte_NOVA_" + fechaStr + ".xlsx";
        
        //Obtener la ruta del escritorio del usuario actual
        String rutaEscritorio = System.getProperty("user.home") + java.io.File.separator + "Desktop";
        java.io.File carpetaNOVA = new java.io.File(rutaEscritorio, "NOVA_Reportes_y_Facturas");
                
        //si la carpeta no existe, la crea
        if(!carpetaNOVA.exists()){
            carpetaNOVA.mkdirs();
        }
        
        //nombrando la carpeta y el nombre del archivo 
        String rutaCompletaExcel = new java.io.File(carpetaNOVA, nombreArchivo).getAbsolutePath();
        boolean exito = reporte.exportarExcelNativo(rutaCompletaExcel, encabezados, datos);//generando el reporte con su nombre, encabezados y datos
        if(exito){
            JOptionPane.showMessageDialog(this, "Reporte exportado exitosamente como: \n" + nombreArchivo);
        }
        else{
            JOptionPane.showMessageDialog(this, "Error al generar el reporte Excel.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGenerarReporteActionPerformed

