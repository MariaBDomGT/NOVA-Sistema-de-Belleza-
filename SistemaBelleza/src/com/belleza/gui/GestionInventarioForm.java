    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try{
            int fila = tbInventario.getSelectedRow();//para seleccionar la fila de la tabla
            
            //si el usuario no toca una fila
            if(fila == -1){
                JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            int id = (int) modeloTabla.getValueAt(fila, 0);//mostrando la primera fila de la tabla
            
            //mensaje de confirmacion
            int confirm = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el producto ID " + id + "?", "Confirmar", JOptionPane.YES_NO_OPTION);
            if(confirm == JOptionPane.YES_OPTION){//si el usuario selecciono "yes"
                try{
                    inventarioDAO.eliminarProducto(id);
                    authService.getInventario().removeIf(p -> p.getIdProducto() == id);
                    cargaDatosTabla();
                    JOptionPane.showMessageDialog(this, "Producto Elminado");
                }
                catch(SQLException ex){
                    JOptionPane.showMessageDialog(this, "Error al Eliminar: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

