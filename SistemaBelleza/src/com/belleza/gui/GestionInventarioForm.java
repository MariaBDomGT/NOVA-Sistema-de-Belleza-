    private void cargaDatosTabla(){
        modeloTabla.setRowCount(0);//devuelve la cantidad de filas

        //recorriendo el inventario
        for(Producto p : authService.getInventario()){
            modeloTabla.addRow(new Object[]{
               p.getIdProducto(),
                p.getNombre(),
                p.getMarca(),
                String.format("Q%.2f", p.getPrecioVenta()),
                p.getStock(),
                p.getStockMinimo(),
                p.getTipo()
            });
        }
        
        //cambiando la fuente de la tabla
        tbInventario.getTableHeader().setFont(new java.awt.Font("Sitka Text", 1, 13));
        tbInventario.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
        
        for(int a = 0; a < tbInventario.getModel().getColumnCount(); a++){
            javax.swing.table.TableColumn columna = tbInventario.getColumnModel().getColumn(a);
            
            int anchoEncabezado = tbInventario.getTableHeader().getFontMetrics(tbInventario.getTableHeader().getFont()).stringWidth(tbInventario.getColumnName(a))+50;
            int anchoMaximoDatos = anchoEncabezado;
            for(int fila = 0; fila < tbInventario.getRowCount(); fila++){
                Object valor = tbInventario.getValueAt(fila, a);
                if(valor != null){
                    int anchoCelda = tbInventario.getFontMetrics(tbInventario.getFont()).stringWidth(valor.toString())+20;
                    if(anchoCelda > anchoMaximoDatos){
                        anchoMaximoDatos = anchoCelda;
                    }
                }
            }
            
            columna.setPreferredWidth(anchoMaximoDatos);
        }
    }

